#!/usr/bin/env python3
# Bake a real TTF into backend/bench_font.h for the EGUI_BENCH sokol-side
# overlay (backend/sokol_shim.c) — the old hand-rolled 3x5 pixel font is
# gone; this renders ASCII 32..126 with PIL at a small size and emits:
#   - a WxH alpha bitmap (coverage, one byte per texel, row-major)
#   - per-glyph metrics: atlas x/y/w/h, bearing from the ascender line,
#     advance (in 1/4 px)
# The shim expands the alpha plane into an RGBA8 atlas at runtime
# (RGB=255, A=coverage — sokol_gl's FS multiplies texture*color, so the
# coverage must live in the alpha channel).
#
# Regenerate:  python3 scripts/make_bench_font.py
import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TTF = os.path.join(ROOT, "assets", "fonts", "NotoSans-Regular.ttf")
OUT = os.path.join(ROOT, "backend", "bench_font.h")
PX = 13          # bake size (overlay draws 1 texel = 1 point)
FIRST, LAST = 32, 126
PAD = 3          # canvas padding around the anchor (bearings can be < 0)
GAP = 1          # empty texels between packed glyphs (linear-filter bleed)
ROW_MAX = 384    # atlas max width

font = ImageFont.truetype(TTF, PX)
ascent, descent = font.getmetrics()

glyphs = []
for cp in range(FIRST, LAST + 1):
    ch = chr(cp)
    canvas = Image.new("L", (PX * 3 + 2 * PAD, ascent + descent + 2 * PAD), 0)
    ImageDraw.Draw(canvas).text((PAD, PAD), ch, font=font, fill=255)
    bbox = canvas.getbbox()  # None for ' ' etc.
    adv = font.getlength(ch)
    if bbox is None:
        glyphs.append(None)
        continue
    glyphs.append({
        "bmp": canvas.crop(bbox),
        "x0": bbox[0] - PAD,   # bearing from the ascender line (px)
        "y0": bbox[1] - PAD,
        "adv": adv,
    })

# shelf packer: one row at a time, tallest glyph sets the row height
atlas_w, atlas_h, row_h, x, y = 0, 0, 0, 0, 0
for g in glyphs:
    if g is None:
        continue
    w, h = g["bmp"].size
    if x + w > ROW_MAX:
        atlas_w = max(atlas_w, x)
        y += row_h + GAP
        x, row_h = 0, 0
    g["ax"], g["ay"] = x, y
    x += w + GAP
    row_h = max(row_h, h)
    atlas_w = max(atlas_w, x)
atlas_h = y + row_h

plane = Image.new("L", (atlas_w, atlas_h), 0)
for g in glyphs:
    if g is not None:
        plane.paste(g["bmp"], (g["ax"], g["ay"]))
alpha = plane.tobytes()

def c_array(data, per_line):
    out = []
    for i in range(0, len(data), per_line):
        out.append("    " + ",".join(str(b) for b in data[i:i + per_line]) + ",")
    return "\n".join(out)

metrics = []
for g in glyphs:
    if g is None:
        metrics.append("    {0,0,0,0,0,0,0},")
    else:
        metrics.append("    {%d,%d,%d,%d,%d,%d,%d}," % (
            g["ax"], g["ay"], g["bmp"].size[0], g["bmp"].size[1],
            g["x0"], g["y0"], round(g["adv"] * 4)))

with open(OUT, "w") as f:
    f.write("""\
// Generated by scripts/make_bench_font.py from assets/fonts/%s —
// DO NOT EDIT; regenerate with `python3 scripts/make_bench_font.py`.
// Alpha coverage plane + metrics for the EGUI_BENCH sokol-side overlay
// (backend/sokol_shim.c, sh_bench_text). Glyphs are rendered at %dpx;
// adv4 is the advance in 1/4 px; x0/y0 are the bearing from the
// ASCENDER line (anchor semantics of PIL's "la" anchor).
#pragma once
#define BENCH_FONT_FIRST %d
#define BENCH_FONT_N %d
#define BENCH_FONT_W %d
#define BENCH_FONT_H %d
#define BENCH_FONT_ASCENT %d
#define BENCH_FONT_DESCENT %d

typedef struct {
    unsigned short x, y;     // atlas texel of the glyph's top-left
    unsigned char w, h;      // glyph size in texels
    signed char x0, y0;      // bearing from the ascender line (px)
    unsigned char adv4;      // advance in 1/4 px
} bench_glyph_t;

static const bench_glyph_t bench_font_g[BENCH_FONT_N] = {
%s
};

static const unsigned char bench_font_a[BENCH_FONT_W * BENCH_FONT_H] = {
%s
};
""" % (os.path.basename(TTF), PX, FIRST, LAST - FIRST + 1, atlas_w, atlas_h,
       ascent, descent, "\n".join(metrics), c_array(alpha, 32)))

print("baked %s: %dx%d atlas, %d glyphs, %d alpha bytes" %
      (OUT, atlas_w, atlas_h, len(glyphs), len(alpha)))
